#!/usr/bin/env node
/* ============================================================
   Concept Lab — icons.js builder
   ------------------------------------------------------------
   Embeds the two SVG sprites (assets/icons/sprite.svg and
   assets/icons/tabler-sprite.svg) directly into assets/js/icons.js
   so the site needs NO network and NO server: it works when opened
   straight from disk (file://).

   Why: external <use href="file.svg#id"> is blocked on file://,
   and loading the sprite with XMLHttpRequest is also blocked by
   the browser's same-origin policy on file://. Embedding the
   markup sidesteps both, keeping the course fully offline.

   Run:  node tools/build-icons-js.js
   ============================================================ */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SPRITE = path.join(ROOT, "assets/icons/sprite.svg");
const TABLER = path.join(ROOT, "assets/icons/tabler-sprite.svg");
const OUT = path.join(ROOT, "assets/js/icons.js");

/* Drop HTML comments so the embedded markup stays compact. */
function stripComments(s) {
  return s.replace(/<!--[\s\S]*?-->/g, "").trim();
}

/* Escape a string for safe embedding inside a JS template literal. */
function esc(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const sprite = esc(stripComments(fs.readFileSync(SPRITE, "utf8")));
const tabler = esc(stripComments(fs.readFileSync(TABLER, "utf8")));

const out = `/* ============================================================
   Concept Lab — local SVG icon helper (self-contained)
   ------------------------------------------------------------
   The two SVG sprites are embedded directly in this file so the
   site needs NO network and NO server: it works when opened
   straight from disk (file://). External <use href="file.svg#id">
   references are blocked on file://, so we inline the sprite
   markup into the document and reference symbols by id instead.

   Usage:
     <svg class="ic"><use href="#i-search"/></svg>

   Exposes window.Icons = { mount, svg, tabler }.
     Icons.svg("search", "ic")  ->  '<svg class="ic"><use href="#i-search"/></svg>'

   Generated by tools/build-icons-js.js — do not edit by hand.
   ============================================================ */
(function (global) {
  "use strict";

  /* Sprite markup, embedded at build time from
     assets/icons/sprite.svg and assets/icons/tabler-sprite.svg.
     Regenerate with: node tools/build-icons-js.js */
  var SPRITE_MARKUP = \`${sprite}\`;

  var TABLER_MARKUP = \`${tabler}\`;

  var mounted = false;

  /* Inline a sprite's markup into a hidden holder at the top of
     <body>. No fetch/XHR — the markup is already in memory, so
     this works from file:// with no server. */
  function inline(markup, holderId) {
    if (document.getElementById(holderId)) return;
    var holder = document.createElement("div");
    holder.id = holderId;
    holder.setAttribute("aria-hidden", "true");
    holder.style.display = "none";
    holder.innerHTML = markup;
    document.body.insertBefore(holder, document.body.firstChild);
  }

  /* Inline both sprites once, at the top of <body>. */
  function mount() {
    if (mounted) return;
    mounted = true;
    inline(SPRITE_MARKUP, "cl-icon-sprite");
    inline(TABLER_MARKUP, "cl-tabler-sprite");
  }

  /* Build an inline <svg> string for a named UI icon (sprite.svg). */
  function svg(name, cls) {
    return '<svg class="' + (cls || "ic") + '" aria-hidden="true">' +
      '<use href="#i-' + name + '"/></svg>';
  }

  /* Build an inline <svg> string for a named Tabler icon. */
  function tabler(name, cls) {
    return '<svg class="' + (cls || "ic") + '" aria-hidden="true">' +
      '<use href="#tb-' + name + '"/></svg>';
  }

  global.Icons = { mount: mount, svg: svg, tabler: tabler };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", mount);
  } else {
    mount();
  }
})(window);
`;

fs.writeFileSync(OUT, out);
console.log("wrote " + path.relative(ROOT, OUT) + " (" + out.length + " bytes)");
